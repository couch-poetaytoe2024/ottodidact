import { z } from 'zod';
import { MIN_SELECTION } from './selection';
const id=z.string().min(1).max(200);
export const commandSchema=z.discriminatedUnion('type',[
  z.object({type:z.literal('capture')}).strict(),
  z.object({type:z.literal('cancel')}).strict(),
  z.object({type:z.literal('dismiss')}).strict(),
  z.object({type:z.literal('quit')}).strict(),
  z.object({type:z.literal('clear')}).strict(),
  z.object({type:z.literal('closeBranch'),branchId:id.optional()}).strict(),
  z.object({type:z.literal('expandBranch'),branchId:id,expanded:z.boolean()}).strict(),
  z.object({type:z.literal('minimizeBranch'),branchId:id,minimized:z.boolean()}).strict(),
  z.object({type:z.literal('branchLayout'),branchId:id,expanded:z.boolean(),minimized:z.boolean(),collapsed:z.object({width:z.number().int().min(100).max(440),height:z.number().int().min(45).max(160)}).strict().optional(),measurements:z.array(z.object({width:z.number().int().min(100).max(440),height:z.number().int().min(45).max(100000)}).strict()).min(1).max(5)}).strict(),
  z.object({type:z.literal('settings')}).strict(),
  z.object({type:z.literal('closeSettings')}).strict(),
  z.object({type:z.literal('mainChat')}).strict(),
  z.object({type:z.literal('questionPanel')}).strict(),
  z.object({type:z.literal('glowMode'),mode:z.enum(['always','needed'])}).strict(),
  z.object({type:z.literal('finishLauncherMove')}).strict(),
  z.object({type:z.literal('moveLauncher'),dx:z.number().finite().min(-10000).max(10000),dy:z.number().finite().min(-10000).max(10000)}).strict(),
  z.object({type:z.literal('retry')}).strict(),
  z.object({type:z.literal('refreshProvider')}).strict(),
  z.object({type:z.literal('tutorMode'),mode:z.enum(['hint','explain'])}).strict(),
  z.object({type:z.literal('questionHeight'),height:z.number().int().min(108).max(480)}).strict(),
  z.object({type:z.literal('mainHeight'),height:z.number().int().min(300).max(900)}).strict(),
  z.object({type:z.literal('minimizeMain'),minimized:z.boolean()}).strict(),
  z.object({type:z.literal('select'),selectionId:id,rect:z.object({x:z.number().finite().nonnegative(),y:z.number().finite().nonnegative(),width:z.number().finite().min(MIN_SELECTION),height:z.number().finite().min(MIN_SELECTION)}).strict()}).strict(),
  z.object({type:z.literal('explain'),question:z.string().trim().min(1).max(2000),mode:z.enum(['hint','explain']).optional()}).strict(),
  z.object({type:z.literal('openBranch'),annotationId:id}).strict(),
  z.object({type:z.literal('annotationAttention'),annotationId:id,channel:z.enum(['hover','focus']),active:z.boolean()}).strict(),
  z.object({type:z.literal('resumeBranch'),branchId:id}).strict(),
  z.object({type:z.literal('send'),branchId:id.optional(),text:z.string().trim().min(1).max(2000)}).strict(),
  z.object({type:z.literal('bring'),branchId:id,messageId:id}).strict(),
]);
